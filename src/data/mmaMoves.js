// Timeline di una sequenza: partenza in guardia, colpi concatenati, pausa finale.
// tag = indice del colpo nella combo (per evidenziare il passo in corso).
export function comboKeys(moveIds, { lead = 700, tail = 900 } = {}) {
  const keys = [{ pose: 'base', move: 350, hold: lead, curve: 'io', tag: -1 }];
  moveIds.forEach((id, index) => (MOVES[id]?.keys || []).forEach((key) => keys.push({ ...key, tag: index })));
  keys.push({ pose: 'base', move: 350, hold: tail, curve: 'io', tag: moveIds.length });
  return keys;
}
